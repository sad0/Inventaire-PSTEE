"""Compose variant J's final background (John 2026-10-22): bg_dressed_2x.png with
- the dressed slot areas darkened to match the rest of the painting (dress_mask_2x.png),
- the gauges and glass tubes put back as static art (no animation),
- the four stat bubbles in Party Stash BG shapes (shield AC, spiked star THAC0, thorned ring HP, ring damage),
  generated by SwarmUI in a steampunk look, cut out of their black background and darkened.
Output: design/art/j/bg_final_2x.png (same 2x reference coordinates as bg_clean_2x.png).
"""
import json
import os

from PIL import Image, ImageChops, ImageDraw, ImageEnhance, ImageFilter

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), ".."))
J = os.path.join(ROOT, "design", "art", "j")
L = json.load(open(os.path.join(ROOT, "design", "build", "layout_j.json"), encoding="utf-8"))
K = 683 / 996
OXJ = L["menu"]["bg_offset"]
STATIC = ["gauge_top", "gauge_left", "gauge_right", "tube_left", "tube_right", "tube_mid"]
BUBBLES = {"AC": "bub_ac_c0_s81", "THAC0": "bub_thac0_c0_s81", "HP": "bub_hp_c0_s82", "Damage": "bub_dmg_c0_s82"}


def S(x, y):
    return ((x - OXJ) / K * 2, y / K * 2)


def cutout(img, thr=24):
    """Flood-fill the near-black background from the borders -> alpha (keeps the dark centre of a frame)."""
    rgb = img.convert("RGB")
    w, h = rgb.size
    key = rgb.point(lambda v: 255 if v > thr else 0).convert("L")
    key = key.point(lambda v: 255 if v else 0)
    m = Image.new("L", (w + 2, h + 2), 0)
    m.paste(key, (1, 1))
    ImageDraw.floodfill(m, (0, 0), 128)
    alpha = m.crop((1, 1, w + 1, h + 1)).point(lambda v: 0 if v == 128 else 255)
    alpha = alpha.filter(ImageFilter.GaussianBlur(1.2))
    out = rgb.convert("RGBA")
    out.putalpha(alpha)
    return out.crop(alpha.getbbox())


def main():
    bg = Image.open(os.path.join(J, "bg_dressed_norings_2x.png")).convert("RGB")  # painted rings inpainted out
    # 1) darken + desaturate the generated copper around the slots
    mask = Image.open(os.path.join(J, "dress_mask_2x.png")).convert("L")
    dark = ImageEnhance.Brightness(ImageEnhance.Color(bg).enhance(0.75)).enhance(0.68)
    bg = Image.composite(dark, bg, mask)
    out = bg.convert("RGBA")
    # 2) static gauges and tubes back in place
    for nm in STATIC:
        p = Image.open(os.path.join(J, "parts", f"{nm}.png")).convert("RGBA")
        x, y, w, h = L["parts"][nm]
        px, py = S(x, y)
        out.alpha_composite(p, (round(px), round(py)))
    # 3) BG-shaped stat bubbles over the painted rings, darker copper, dark centre
    for nm, f in BUBBLES.items():
        b = cutout(Image.open(os.path.join(J, "gen", f + ".png")))
        rgb = ImageEnhance.Brightness(ImageEnhance.Color(b.convert("RGB")).enhance(0.8)).enhance(0.62)
        b2 = rgb.convert("RGBA")
        b2.putalpha(b.getchannel("A"))
        d = L["stats"][nm]["disc"]
        cx, cy = S(d[0] + d[2] / 2, d[1] + d[3] / 2)
        size = round(d[2] / K * 2 * 1.25)
        b2.thumbnail((size, size), Image.LANCZOS)
        out.alpha_composite(b2, (round(cx - b2.width / 2), round(cy - b2.height / 2)))
    # 4) a dark copper coin heap over the painted rosette (John 2026-10-22), ref box 1060-1150 x 893-965
    heap = cutout(Image.open(os.path.join(J, "gen", "coins_c0_s131.png")), thr=34)
    rgb = ImageEnhance.Brightness(heap.convert("RGB")).enhance(0.8)
    h2 = rgb.convert("RGBA")
    h2.putalpha(heap.getchannel("A"))
    h2.thumbnail((300, 300), Image.LANCZOS)
    out.alpha_composite(h2, (round(1105 * 2 - h2.width / 2), round(965 * 2 - h2.height)))
    out.convert("RGB").save(os.path.join(J, "bg_final_2x.png"))
    print("bg_final_2x.png written")


if __name__ == "__main__":
    main()
